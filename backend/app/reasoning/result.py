"""Structured output of the NVIDIA NIM reasoning layer.

The reasoning result is an *explanation* of a policy decision that has
already been made by the deterministic policy engine.  It carries no
authority to change, override, or authorize any recovery action.

If the reasoning layer fails for any reason (NIM API unavailable, timeout,
malformed output), a safe deterministic fallback is returned that preserves
the original policy decision without alteration.
"""

from __future__ import annotations

from pydantic import BaseModel, Field


class ReasoningResult(BaseModel):
    """Structured result from the reasoning layer.

    This model is returned by ``RecoveryReasoner.analyze`` and is always
    safe to use — even when NIM is unreachable — because the factory
    method guarantees a deterministic fallback.

    The ``policy_action_allowed`` field mirrors the policy engine's
    ``automatic_recovery_allowed`` flag and **must never be set to True
    by the reasoning layer when the policy denied recovery**.
    """

    success: bool = Field(
        ...,
        description=(
            "Whether the reasoning call succeeded. False when NIM "
            "was unavailable, timed out, or returned invalid output."
        ),
    )

    recommendation: str = Field(
        ...,
        description=(
            "A short human-readable recommendation. When reasoning "
            "succeeds this is generated by the model; on failure it reflects "
            "the deterministic policy decision."
        ),
    )

    explanation: str = Field(
        ...,
        description=(
            "Detailed explanation of *why* the payment failed and what "
            "the policy decided. On fallback this restates the policy reason."
        ),
    )

    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description=(
            "Confidence in the explanation (0.0–1.0). Set to 0.0 on "
            "fallback because the reasoning layer did not produce output."
        ),
    )

    model_id: str = Field(
        ...,
        description=(
            "The model identifier used for this reasoning call "
            "(e.g. 'meta/llama-3.1-8b-instruct'). Set to 'fallback' when NIM "
            "was not reachable."
        ),
    )

    policy_action_allowed: bool = Field(
        ...,
        description=(
            "Mirror of the policy engine's automatic_recovery_allowed flag. "
            "The reasoning layer MUST NOT set this to True when the policy "
            "denied recovery."
        ),
    )

    is_fallback: bool = Field(
        ...,
        description=(
            "True when the result is a deterministic fallback because NIM "
            "was unavailable or returned invalid output."
        ),
    )

    # --- Operator-facing contribution ------------------------------------
    # These are the model's actual value-add: plain-language framing an
    # operator can act on. All are optional — a missing or invalid field
    # degrades to None rather than failing the whole explanation, and none
    # of them can widen what the policy authorized.

    root_cause_plain: str | None = Field(
        default=None,
        description="Why the payment failed, in operator-friendly language",
    )
    why_appropriate: str | None = Field(
        default=None,
        description="Why the policy's chosen action fits this failure",
    )
    customer_message: str | None = Field(
        default=None,
        description=(
            "Suggested customer-facing copy. Must not state amounts or "
            "promise that recovery is authorized."
        ),
    )
    escalation_summary: str | None = Field(
        default=None,
        description="Short summary for a human reviewer when escalated",
    )

    error: str | None = Field(
        default=None,
        description=(
            "Error message when the reasoning call failed. None on success."
        ),
    )
